/**
 * Tests for the runtime xlsx reader (src/data/xlsx.js).
 *
 * This module is what lets the running game read `player-enemies.xlsx` directly,
 * so it has to survive the two things that actually happen to a hand-edited
 * workbook:
 *
 *  1. Excel's own idea of an .xlsx: a shared string table, entities, rich text
 *     runs and string cells. The project's own writer emits inline strings, so
 *     reading its output would prove nothing about that path; the fixtures here
 *     are authored independently (tests/fixtures/README.md).
 *  2. Author mistakes. The workbook is edited by hand, so a bad cell has to be
 *     reported at the exact sheet and cell instead of quietly becoming a wrong
 *     stat.
 *
 * The fixtures are regenerated by a dev-only Python script kept OUTSIDE this
 * repo; the project itself must stay zero-dependency. They are written
 * deterministically, so the bytes on disk are stable.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

import { readStats } from '../src/data/xlsx.js';

const REPO_ROOT = fileURLToPath(new URL('..', import.meta.url));
const FIXTURES = join(REPO_ROOT, 'tests', 'fixtures');

const fixture = (name) => readFileSync(join(FIXTURES, name));

const EXPECTED_PLAYER = {
  id: 'player',
  kind: 'player',
  name: 'Player & Co',
  glyph: '@',
  maxHp: 99,
  attack: 7,
  defense: 2,
};

const EXPECTED_ENEMIES = {
  archetypes: {
    rat: { name: 'Giant RAT', glyph: 'r', maxHp: 6, attack: 3, defense: 0 },
    goblin: { name: 'Goblin', glyph: 'g', maxHp: 10, attack: 4, defense: 1 },
  },
  spawn: [
    { archetype: 'rat', count: 2 },
    { archetype: 'goblin', count: 1 },
  ],
};

/** The Error a rejected promise carries, or a thrown assertion failure. */
async function rejectionFrom(promiseFactory) {
  try {
    await promiseFactory();
  } catch (err) {
    return err;
  }
  assert.fail('expected the promise to reject, but it resolved');
}

// ---------- the happy path ----------

test('readStats reads an Excel-shaped workbook: shared strings, entities, rich text, string cells, both ZIP methods', async () => {
  const { player, enemies } = await readStats(fixture('excel-shaped.xlsx'));

  assert.deepEqual(player, EXPECTED_PLAYER);
  assert.deepEqual(enemies, EXPECTED_ENEMIES);
});

test('a workbook with no bosses sheet leaves the bosses key absent', async () => {
  // Optionality is expressed as "the section may be ABSENT". The reader must
  // OMIT the key -- not return an empty section -- so schema.js can tell a
  // workbook that has no bosses sheet from one whose sheet is present but empty
  // (which is an error). The shipped fixtures carry no bosses sheet.
  const stats = await readStats(fixture('excel-shaped.xlsx'));

  assert.equal('bosses' in stats, false, 'the key must be omitted, not present as undefined');
  assert.deepEqual(Object.keys(stats), ['player', 'enemies']);
});

test('a workbook with no items/loot sheets leaves those keys absent too', async () => {
  // Same contract as `bosses`, for the same reason: the fixtures were authored
  // before equipment existed and cannot be regenerated here. An absent key is
  // what lets schema.js default the section to an empty catalog/table.
  const stats = await readStats(fixture('excel-shaped.xlsx'));

  assert.equal('items' in stats, false);
  assert.equal('loot' in stats, false);
});

test('a sheet without the new stat columns omits those keys instead of inventing 0', async () => {
  // This is the property the whole optional-column design exists for: an older
  // workbook (the fixtures) keeps loading. The reader must NOT write `xp: 0`
  // into the result — "absent" and "declared as 0" then default identically in
  // schema.js, but the reader's job is to pass through what the sheet says.
  const { player, enemies } = await readStats(fixture('excel-shaped.xlsx'));

  for (const key of ['maxMana', 'critChance', 'critDamage', 'luck', 'dodge', 'intelligence']) {
    assert.equal(key in player, false, `player.${key} must be omitted when the column is absent`);
  }
  for (const key of ['maxMana', 'xp', 'critChance', 'critDamage', 'dodge', 'intelligence']) {
    assert.equal(
      key in enemies.archetypes.rat,
      false,
      `enemies.archetypes.rat.${key} must be omitted when the column is absent`,
    );
  }
});

test('the SHIPPED workbook reads back the item, loot and stat columns it was written with', async () => {
  // The reader and tools/xlsx-write.mjs must agree on the sheet layout: the writer
  // produces `player-enemies.xlsx`, the page reads it at runtime. Reading the real
  // workbook (not a fixture) is what catches a column added to one and not the
  // other — the failure mode is silent, a stat that quietly reads 0.
  const stats = await readStats(readFileSync(join(REPO_ROOT, 'player-enemies.xlsx')));

  assert.equal('items' in stats, true, 'the shipped workbook must declare an items sheet');
  assert.equal('loot' in stats, true, 'the shipped workbook must declare a loot sheet');
  assert.equal(stats.player.critChance, 5);
  assert.equal(stats.player.dodge, 0);
  assert.equal(stats.player.intelligence, 0);
  assert.equal(stats.player.maxMana, 30, 'the player mana pool round-trips');
  assert.equal(stats.enemies.archetypes.rat.xp, 15);
  assert.equal(stats.enemies.archetypes.rat.maxMana, 0);
  assert.equal(stats.bosses.archetypes.boss.xp, 100);

  const item = stats.items.definitions['rusty-sword'];
  assert.equal(item.slot, 'weapon');
  assert.equal(item.attack, 2);
  assert.equal(item.luck, 0);
  assert.equal(item.dodge, 0);
  assert.equal(item.maxMana, 0);
  assert.equal(stats.items.definitions['worn-boots'].dodge, 5, 'an item may grant the dodge stat');

  // Every loot row must survive as a real reference: the writer refuses to export
  // a dangling one, and the reader must not mangle the wildcard.
  assert.ok(stats.loot.length > 0);
  assert.ok(stats.loot.some((row) => row.enemy === '*'), 'the wildcard row must round-trip');
  for (const row of stats.loot) {
    if (row.enemy !== '*') {
      assert.ok(
        stats.enemies.archetypes[row.enemy] || stats.bosses.archetypes[row.enemy],
        `loot row names a real archetype: ${row.enemy}`,
      );
    }
    assert.ok(stats.items.definitions[row.item], `loot row names a real item: ${row.item}`);
  }

  // The sprite structure: the sheet and its columns exist, the paths may still
  // be empty (the author fills them in by hand), and an empty cell must OMIT
  // the key rather than read as an empty path.
  assert.equal('biomas' in stats, true, 'the shipped workbook must declare a biomas sheet');
  assert.equal(typeof stats.biomas, 'object');
  for (const id of Object.keys(stats.biomas)) {
    assert.ok(['pared1', 'piso1'].includes(id), `biomas: unexpected row id ${id}`);
    assert.ok(stats.biomas[id].length > 0, `biomas.${id}: a present path must not be empty`);
  }
  for (const [label, spritePath] of [
    ['player', stats.player.spritePath],
    ['enemies.archetypes.rat', stats.enemies.archetypes.rat.spritePath],
    ['bosses.archetypes.boss', stats.bosses.archetypes.boss.spritePath],
    ['items.definitions.rusty-sword', stats.items.definitions['rusty-sword'].spritePath],
  ]) {
    if (spritePath !== undefined) {
      assert.equal(typeof spritePath, 'string', `${label}.spritePath must be a string when present`);
      assert.ok(spritePath.length > 0, `${label}.spritePath must not be an empty string`);
    }
  }
});

test('the shared-string and inline-string container styles decode to the SAME objects', async () => {
  // A workbook stores its strings either in sharedStrings.xml (t="s") or inline
  // in <is> (t="inlineStr"). Which one you get depends on the tool that last
  // saved the file: the project's own writer and openpyxl both emit inline
  // strings, real Excel emits shared ones. The reader must not care.
  const shared = await readStats(fixture('excel-shaped.xlsx'));
  const inline = await readStats(fixture('excel-shaped-inline.xlsx'));

  assert.deepEqual(inline, shared, 'the string container must not change the result');
  assert.deepEqual(inline.player, EXPECTED_PLAYER);
  assert.deepEqual(inline.enemies, EXPECTED_ENEMIES);
});

test('the decoded values prove WHICH path ran, not just that something parsed', async () => {
  const { player, enemies } = await readStats(fixture('excel-shaped.xlsx'));

  // "Player &amp; Co" in the shared string table: an entity must be decoded.
  assert.equal(player.name, 'Player & Co', 'an XML entity inside a shared string must be decoded');

  // The rat name is stored as two <r><t> runs, "Giant " and "RAT": collapsing
  // them is how a rich-text cell is read. Taking only the first run would give
  // "Giant ", which is why this is pinned rather than merely non-empty.
  assert.equal(enemies.archetypes.rat.name, 'Giant RAT', 'rich text runs must be concatenated');

  // The rat glyph is a t="str" cell, a different branch from t="s".
  assert.equal(enemies.archetypes.rat.glyph, 'r', 'a t="str" cell must be read');

  // Numbers carry no `t` attribute at all.
  assert.equal(player.maxHp, 99, 'a bare numeric cell must be read as a number');

  // The player row stores E2 before A2 on purpose: the reader must key cells by
  // their column reference, not by the order they appear in the XML.
  assert.equal(player.id, 'player', 'cells out of column order must still map to the right field');
  assert.equal(player.attack, 7);
  assert.equal(player.defense, 2);
});

test('readStats accepts a Node Buffer, a Uint8Array and an ArrayBuffer alike', async () => {
  const buffer = fixture('excel-shaped.xlsx');
  assert.ok(Buffer.isBuffer(buffer), 'readFileSync gives a Buffer');

  const exact = buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength);
  const bytes = [
    ['Buffer', buffer],
    ['Uint8Array', new Uint8Array(exact)],
    ['ArrayBuffer', exact],
  ];

  for (const [label, input] of bytes) {
    const { player, enemies } = await readStats(input);
    assert.deepEqual(player, EXPECTED_PLAYER, `${label}: player`);
    assert.deepEqual(enemies, EXPECTED_ENEMIES, `${label}: enemies`);
  }
});

test('reading a workbook does not mutate the bytes it was handed', async () => {
  const buffer = fixture('excel-shaped.xlsx');
  const before = Buffer.from(buffer);

  await readStats(buffer);

  assert.deepEqual(buffer, before, 'the input buffer must come back untouched');
});

// ---------- author mistakes get a location ----------

test('a text cell where a number belongs is reported at the sheet and cell', async () => {
  const err = await rejectionFrom(() => readStats(fixture('excel-shaped-bad-number.xlsx')));

  assert.ok(err instanceof Error, `expected an Error, got ${err && err.name}`);
  assert.ok(
    err.message.includes('player!G2'),
    `the offending cell must be named so the author can find it in Excel, got: ${err.message}`,
  );
  assert.ok(
    err.message.includes('defense'),
    `the field being read must be named, got: ${err.message}`,
  );
});

test('a sheet missing a required column is rejected, naming the column', async () => {
  const err = await rejectionFrom(() => readStats(fixture('excel-shaped-bad-header.xlsx')));

  assert.ok(err instanceof Error, `expected an Error, got ${err && err.name}`);
  assert.ok(
    err.message.includes('defense'),
    `the missing column must be named, got: ${err.message}`,
  );
  assert.ok(
    err.message.includes('player'),
    `the sheet must be named, got: ${err.message}`,
  );
});

test('a missing sheet is rejected, naming the sheet', async () => {
  const err = await rejectionFrom(() => readStats(fixture('excel-shaped-missing-sheet.xlsx')));

  assert.ok(err instanceof Error, `expected an Error, got ${err && err.name}`);
  assert.ok(
    err.message.includes('enemies'),
    `the missing sheet must be named, got: ${err.message}`,
  );
});

// ---------- not a workbook at all ----------

test('input that is not a ZIP fails loudly instead of hanging or returning junk', async () => {
  for (const [label, input] of [
    ['plain text', Buffer.from('this is not a zip file at all')],
    ['empty', Buffer.alloc(0)],
    ['truncated ZIP header', Buffer.from([0x50, 0x4b, 0x03, 0x04, 0x00])],
  ]) {
    const err = await rejectionFrom(() => readStats(input));
    assert.ok(err instanceof Error, `${label}: expected an Error, got ${err && err.name}`);
    assert.ok(err.message.length > 0, `${label}: the failure must say something`);
  }
});

test('a valid ZIP that is not a workbook fails loudly instead of returning junk', async () => {
  const err = await rejectionFrom(() => readStats(fixture('not-a-workbook.xlsx')));

  assert.ok(err instanceof Error, `expected an Error, got ${err && err.name}`);
  assert.ok(err.message.length > 0, 'the failure must say something');
});
